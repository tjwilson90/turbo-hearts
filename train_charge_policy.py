#!/usr/bin/env python3
"""Fit first-opportunity human charge probabilities, conditional on suit length.

Only Classic, non-keeper hands: ownership is stable between passing and charge
observations. Fit on training games, select shrinkage on validation, then report
test likelihood. Negative examples are held, eligible cards not charged on that
first opportunity, not cards the player didn't hold or couldn't charge.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np

SEATS = ("north", "east", "south", "west")
CARDS = ("QS", "AH", "JD", "TC")


def examples(games):
    rows = []
    for game in games:
        if game["events"][0]["rules"] != "classic":
            continue
        hands, seen, charged, eligible = {}, set(), set(), False
        for event in game["events"]:
            kind = event["type"]
            if kind == "deal":
                hands = {s: set(event[s]) for s in SEATS}
                seen, charged = set(), set()
                eligible = event["pass"] != "keeper"
            elif kind == "send_pass":
                hands[event["from"]].difference_update(event["cards"])
            elif kind == "recv_pass":
                hands[event["to"]].update(event["cards"])
            elif kind == "charge":
                seat = event["seat"]
                if eligible and seat not in seen and game["humans"][SEATS.index(seat)]:
                    hand = hands[seat]
                    for index, card in enumerate(CARDS):
                        if card in hand and card not in charged:
                            length = sum(c[-1] == card[-1] for c in hand)
                            rows.append([game["id"], game["split"], index, length,
                                         int(card in event["cards"])])
                seen.add(seat)
                charged.update(event["cards"])
    return np.asarray(rows, dtype=int).reshape(-1, 5)


def fit(rows, shrinkage):
    # Suit-length bins: 1-3, 4, 5, 6, 7+. Pool rare lengths toward each card's
    # overall rate; do not impose monotonicity or the same rate for every card.
    counts = np.zeros((4, 5, 2), dtype=int)
    for _, _, card, length, outcome in rows:
        counts[card, np.clip(length - 3, 0, 4), outcome] += 1
    prior = (counts[:, :, 1].sum(axis=1) + 1) / (counts.sum(axis=(1, 2)) + 2)
    probabilities = (counts[:, :, 1] + shrinkage * prior[:, None]) / (
        counts.sum(axis=2) + shrinkage)
    return np.clip(probabilities, .02, .98), prior, counts


def metrics(rows, probabilities, prior):
    p = probabilities[rows[:, 2], np.clip(rows[:, 3] - 3, 0, 4)]
    base = prior[rows[:, 2]]
    y = rows[:, 4]
    nll = lambda q: float(-(y*np.log(q)+(1-y)*np.log1p(-q)).mean())
    return {"decisions": len(rows), "games": len(np.unique(rows[:, 0])),
            "nll": nll(p), "constant_by_card_nll": nll(base),
            "brier": float(((p-y)**2).mean())}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("games", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    with args.games.open() as f:
        rows = examples(json.loads(line) for line in f)
    splits = [rows[rows[:, 1] == s] for s in range(3)]
    assert all(len(s) for s in splits)
    assert all(not set(a[:, 0]) & set(b[:, 0]) for a, b in
               [(splits[0], splits[1]), (splits[0], splits[2]), (splits[1], splits[2])])
    candidates = []
    for shrinkage in [4, 16, 64, 256]:
        p, prior, counts = fit(splits[0], shrinkage)
        candidates.append((metrics(splits[1], p, prior)["nll"], shrinkage, p))
    _, shrinkage, p = min(candidates, key=lambda c: c[0])
    descriptions = {}
    for i, card in enumerate(CARDS):
        r = rows[rows[:, 2] == i]
        charged = r[r[:, 4] == 1]
        descriptions[card] = {"holdings": len(r), "charged": len(charged),
            "mean_length_held": float(r[:, 3].mean()),
            "mean_length_charged": float(charged[:, 3].mean())}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("// Generated by train_charge_policy.py; first human charging opportunity.\n"
        + "// QS, AH, JD, TC; suit lengths 1-3, 4, 5, 6, 7+.\n"
        + "pub const PROBABILITIES: [[f64; 5]; 4] = " + json.dumps(p.tolist()) + ";\n")
    report = {"scope": "human first opportunity; Classic non-keeper; stable post-pass hand",
        "split": "chronological whole games 70/15/15", "shrinkage": shrinkage,
        "validation_candidates": [{"shrinkage": s, "nll": loss} for loss, s, _ in candidates],
        "probabilities": p.tolist(), "training_counts": counts.tolist(),
        "metrics_train_validation_test": [metrics(s, p, prior) for s in splits],
        "descriptive_all_splits": descriptions,
        "data_sha256": hashlib.sha256(args.games.read_bytes()).hexdigest()}
    args.output.with_suffix('.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
