#!/usr/bin/env python3
"""Conditional softmax over legal moves; fit successful humans, no value labels."""
import argparse,json,hashlib
from pathlib import Path
import numpy as np


def loss_gradient(rows,starts,weights,regularization=0):
    counts=np.diff(np.r_[starts,len(rows)])
    context,actions=rows[:,7:25],rows[:,25:49]
    logits=((context@weights)*actions).sum(axis=1)
    shifted=logits-np.repeat(np.maximum.reduceat(logits,starts),counts)
    probabilities=np.exp(shifted)
    probabilities/=np.repeat(np.add.reduceat(probabilities,starts),counts)
    chosen=rows[:,4]
    loss=-(np.log(np.maximum(probabilities,1e-100))*chosen).sum()/len(starts)
    grad=context.T@((probabilities-chosen)[:,None]*actions)/len(starts)
    return float(loss+regularization*(weights**2).sum()/2),grad+regularization*weights


def starts_for(rows):
    return np.r_[0,np.flatnonzero(np.diff(rows[:,3]))+1]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('data',type=Path);parser.add_argument('output',type=Path)
    parser.add_argument('--epochs',type=int,default=60)
    args=parser.parse_args()
    rows=np.fromfile(args.data,dtype='<f4').reshape(-1,49)
    splits=[rows[(rows[:,1]==s)&(rows[:,2]==1)] for s in range(3)]
    assert all(len(s) for s in splits)
    assert all(not set(a[:,0])&set(b[:,0]) for a,b in [(splits[0],splits[1]),(splits[0],splits[2]),(splits[1],splits[2])])
    train=splits[0];starts=starts_for(train);ends=np.r_[starts[1:],len(train)]
    validation=splits[1];val_starts=starts_for(validation)
    weights=np.zeros((18,24));m=np.zeros_like(weights);v=np.zeros_like(weights)
    best=float('inf');step=0;history=[];rng=np.random.default_rng(43)
    for epoch in range(1,args.epochs+1):
        order=rng.permutation(len(starts))
        for offset in range(0,len(order),1024):
            groups=order[offset:offset+1024]
            sizes=ends[groups]-starts[groups]
            idx=np.concatenate([np.arange(starts[i],ends[i]) for i in groups])
            batch=train[idx]
            batch_starts=np.r_[0,np.cumsum(sizes)[:-1]]
            _,grad=loss_gradient(batch,batch_starts,weights,.001)
            step+=1;m=.9*m+.1*grad;v=.999*v+.001*grad**2
            weights-=.01*(m/(1-.9**step))/(np.sqrt(v/(1-.999**step))+1e-8)
        val=loss_gradient(validation,val_starts,weights)[0]
        if val<best:best,best_epoch,selected=val,epoch,weights.copy()
        history.append({'epoch':epoch,'validation_nll':val})
        if epoch%10==0:print(json.dumps(history[-1]),flush=True)
    metrics=[]
    for split in range(3):
        for skilled in [0,1]:
            b=rows[(rows[:,1]==split)&(rows[:,2]==skilled)];s=starts_for(b)
            metrics.append({'split':split,'selected_players':bool(skilled),'decisions':len(s),
                'nll':loss_gradient(b,s,selected)[0],
                'general_mixture_nll':float(-np.log(b[s,5]).mean()),
                'skilled_mixture_nll':float(-np.log(b[s,6]).mean())})
    args.output.write_text('// Generated by train_human_action.py; conditional human action probabilities.\n'
        +'pub const WEIGHTS: [[f64;24];18] = '+json.dumps(selected.tolist())+';\n')
    report={'role':'successful human conditional move model','best_epoch':best_epoch,'seed':43,
        'regularization':.001,'metrics':metrics,'history':history,'weights':selected.tolist(),
        'data_sha256':hashlib.sha256(args.data.read_bytes()).hexdigest()}
    args.output.with_suffix('.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({'best_epoch':best_epoch,'metrics':metrics}),flush=True)


if __name__=='__main__':main()
