#!/usr/bin/env python3
"""Fit a contextual mixture to human choices, with game-level temporal splits.

Components: uniform legal, heuristic, duck, shooting, preventive defense.
Outputs are action probabilities, not value estimates. Validation chooses the
epoch; the final test block is evaluated once, after selection.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np


def loss_gradient(x, likelihood, weights, regularization=0.0001):
    logits = x @ weights.T
    gate = np.exp(logits - logits.max(axis=1, keepdims=True))
    gate /= gate.sum(axis=1, keepdims=True)
    joint = gate * likelihood
    probability = joint.sum(axis=1, keepdims=True)
    responsibility = joint / probability
    loss = -np.log(probability).mean() + regularization * (weights**2).sum()/2
    gradient = (gate-responsibility).T @ x / len(x) + regularization*weights
    return float(loss), gradient


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    rows = np.fromfile(args.data, dtype="<f4").reshape(-1, 15).astype(np.float64)
    assert len(rows) and np.isfinite(rows).all()
    splits = [rows[rows[:, 1] == split] for split in range(3)]
    assert all(len(s) for s in splits)
    assert all(not set(a[:,0]) & set(b[:,0]) for a,b in [(splits[0],splits[1]),(splits[0],splits[2]),(splits[1],splits[2])])
    weights = np.zeros((5,8))
    weights[:,0] = np.log([.05,.6,.15,.1,.1])
    m,v = np.zeros_like(weights),np.zeros_like(weights)
    rng = np.random.default_rng(args.seed)
    best, step, history = float("inf"), 0, []
    for epoch in range(1,args.epochs+1):
        train = splits[0][rng.permutation(len(splits[0]))]
        for start in range(0,len(train),2048):
            batch = train[start:start+2048]
            _, grad = loss_gradient(batch[:,2:10],batch[:,10:],weights)
            step += 1
            m = .9*m+.1*grad
            v = .999*v+.001*grad**2
            weights -= .02*(m/(1-.9**step))/(np.sqrt(v/(1-.999**step))+1e-8)
        val = loss_gradient(splits[1][:,2:10],splits[1][:,10:],weights,0)[0]
        history.append({"epoch":epoch,"validation_nll":val})
        if val < best:
            best,best_epoch,selected = val,epoch,weights.copy()
        if epoch%10==0: print(json.dumps(history[-1]),flush=True)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text("// Generated by train_human_policy.py; action-probability mixture, not money.\n"
        +"pub const WEIGHTS: [[f64; 8]; 5] = "+json.dumps(selected.tolist())+";\n")
    metrics=[]
    for split in splits:
        likelihood=split[:,10:]
        # Same 25%-uniform noise used by existing behavioral inference.
        metrics.append({"games":len(np.unique(split[:,0])),"decisions":len(split),
            "fitted_nll":loss_gradient(split[:,2:10],likelihood,selected,0)[0],
            "heuristic_nll":float(-np.log(.25*likelihood[:,0]+.75*likelihood[:,1]).mean()),
            "prior_nll":float(-np.log(.25*likelihood[:,0]+.75*(likelihood[:,1:4]@np.array([.9,.05,.05]))).mean()),
            "uniform_nll":float(-np.log(likelihood[:,0]).mean())})
    report={"role":"human_action_probability","split":"chronological whole games 70/15/15",
        "seed":args.seed,"best_epoch":best_epoch,"epochs":args.epochs,"regularization":.0001,
        "metrics_train_validation_test":metrics,"weights":selected.tolist(),
        "sha256":hashlib.sha256(args.output.read_bytes()).hexdigest(),
        "data_sha256":hashlib.sha256(args.data.read_bytes()).hexdigest(),"history":history}
    args.output.with_suffix('.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({"best_epoch":best_epoch,"metrics":metrics}),flush=True)


if __name__=="__main__":main()
