#!/usr/bin/env python3
"""Fit a contextual policy on the training-only successful-player cohort."""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
from train_human_policy import loss_gradient


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data",type=Path)
    parser.add_argument("output",type=Path)
    parser.add_argument("--epochs",type=int,default=120)
    args=parser.parse_args()
    rows=np.fromfile(args.data,dtype='<f4').reshape(-1,26).astype(float)
    splits=[rows[(rows[:,1]==s)&(rows[:,2]==1)] for s in range(3)]
    assert all(len(s) for s in splits)
    assert all(not set(a[:,0])&set(b[:,0]) for a,b in [(splits[0],splits[1]),(splits[0],splits[2]),(splits[1],splits[2])])
    weights=np.zeros((6,16));weights[:,0]=np.log([.05,.6,.1,.1,.1,.05])
    m,v=np.zeros_like(weights),np.zeros_like(weights)
    rng=np.random.default_rng(42);step=0;best=float('inf');history=[]
    for epoch in range(1,args.epochs+1):
        train=splits[0][rng.permutation(len(splits[0]))]
        for start in range(0,len(train),2048):
            b=train[start:start+2048]
            _,grad=loss_gradient(b[:,3:19],b[:,19:25],weights,.001)
            step+=1;m=.9*m+.1*grad;v=.999*v+.001*grad**2
            weights-=.02*(m/(1-.9**step))/(np.sqrt(v/(1-.999**step))+1e-8)
        val=loss_gradient(splits[1][:,3:19],splits[1][:,19:25],weights,0)[0]
        if val<best:best,best_epoch,selected=val,epoch,weights.copy()
        history.append({"epoch":epoch,"validation_nll":val})
        if epoch%20==0: print(json.dumps(history[-1]),flush=True)
    metrics=[]
    for split in range(3):
        for cohort in [0,1]:
            b=rows[(rows[:,1]==split)&(rows[:,2]==cohort)]
            metrics.append({"split":split,"selected_players":bool(cohort),"decisions":len(b),
                "nll":loss_gradient(b[:,3:19],b[:,19:25],selected,0)[0],
                "previous_human_nll":float(-np.log(b[:,25]).mean())})
    args.output.write_text('// Generated by train_skilled_policy.py; human action probabilities.\n'
        +'pub const WEIGHTS: [[f64; 16]; 6] = '+json.dumps(selected.tolist())+';\n')
    report={"role":"successful human action probability, not value", "best_epoch":best_epoch,
        "seed":42,"regularization":.001,"weights":selected.tolist(),"metrics":metrics,"history":history,
        "data_sha256":hashlib.sha256(args.data.read_bytes()).hexdigest()}
    args.output.with_suffix('.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({"best_epoch":best_epoch,"metrics":metrics}),flush=True)


if __name__=='__main__':main()
